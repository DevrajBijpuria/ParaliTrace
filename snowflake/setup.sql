USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE WAREHOUSE PARALITRACE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND=60
  AUTO_RESUME= TRUE
  INITIALLY_SUSPENDED=TRUE;

CREATE OR REPLACE DATABASE PARALITRACE;
CREATE OR REPLACE SCHEMA PARALITRACE.RAW;
CREATE OR REPLACE SCHEMA PARALITRACE.STAGING;
CREATE OR REPLACE SCHEMA PARALITRACE.SILVER;
CREATE OR REPLACE SCHEMA PARALITRACE.GOLD;
CREATE OR REPLACE SCHEMA PARALITRACE.OPS;

CREATE ROLE IF NOT EXISTS DBT_ROLE;
GRANT USAGE   ON WAREHOUSE PARALITRACE_WH TO ROLE DBT_ROLE;
GRANT OPERATE ON WAREHOUSE PARALITRACE_WH TO ROLE DBT_ROLE;
GRANT ALL     ON DATABASE  PARALITRACE    TO ROLE DBT_ROLE;
GRANT ALL     ON ALL SCHEMAS IN DATABASE PARALITRACE TO ROLE DBT_ROLE;
GRANT ALL     ON FUTURE SCHEMAS IN DATABASE PARALITRACE TO ROLE DBT_ROLE;
GRANT ALL     ON FUTURE TABLES IN DATABASE PARALITRACE TO ROLE DBT_ROLE;
GRANT ALL     ON FUTURE VIEWS  IN DATABASE PARALITRACE TO ROLE DBT_ROLE;

SET my_user = CURRENT_USER();
GRANT ROLE DBT_ROLE TO USER IDENTIFIER($my_user);

create schema if not exists PARALITRACE.ML;
grant usage, create table on schema PARALITRACE.ML to role DBT_ROLE;

CREATE ROLE IF NOT EXISTS PARALITRACE_READER;
GRANT USAGE ON WAREHOUSE PARALITRACE_WH TO ROLE PARALITRACE_READER;
GRANT USAGE ON DATABASE PARALITRACE TO ROLE PARALITRACE_READER;
GRANT USAGE ON SCHEMA PARALITRACE.GOLD TO ROLE PARALITRACE_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA PARALITRACE.GOLD TO ROLE PARALITRACE_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PARALITRACE.GOLD TO ROLE PARALITRACE_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA PARALITRACE.GOLD TO ROLE PARALITRACE_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA PARALITRACE.GOLD TO ROLE PARALITRACE_READER;
SET my_user = CURRENT_USER();
GRANT ROLE PARALITRACE_READER TO USER IDENTIFIER($my_user);

 