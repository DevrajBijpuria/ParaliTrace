CREATE OR REPLACE PIPE PIPE_DEAD_LETTER 
  AUTO_INGEST = TRUE
  AS
  COPY INTO DEAD_LETTER_BRONZE (SOURCE, RECORD, _FILE_NAME, _LOADED_AT) FROM ( SELECT REGEXP_SUBSTR(METADATA$FILENAME, 'source=([a-z]+)', 1, 1, 'e'),$1,
  METADATA$FILENAME,METADATA$START_SCAN_TIME FROM @PARALITRACE_RAW_DEAD_LETTER)
  FILE_FORMAT = (FORMAT_NAME = 'PARALITRACE.RAW.FF_JSON')
  PATTERN = '.*[.]json';
  
ALTER PIPE PARALITRACE.RAW.PIPE_FIRES REFRESH;
ALTER PIPE PARALITRACE.RAW.PIPE_AQ REFRESH;
ALTER PIPE PARALITRACE.RAW.PIPE_WEATHER REFRESH;
