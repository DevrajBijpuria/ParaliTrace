CREATE OR REPLACE PIPE PIPE_FIRES
 AUTO_INGEST=TRUE
 AS
 COPY INTO FIRES_BRONZE FROM @PARALITRACE_RAW_CLEAN/source=firms/
 FILE_FORMAT=(FORMAT_NAME = 'PARALITRACE.RAW.FF_PARQUET')
  PATTERN = '.*[.]parquet'
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  INCLUDE_METADATA = (_FILE_NAME = METADATA$FILENAME, _FILE_ROW_NUMBER = METADATA$FILE_ROW_NUMBER, _LOADED_AT = METADATA$START_SCAN_TIME);

